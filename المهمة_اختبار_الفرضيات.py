
import pandas as pd
import seaborn as sns
from scipy import stats
from scipy.stats import chi2_contingency

# مستوى الدلالة المعتاد
مستوى_الدلالة = 0.05

# ---------- تحميل البيانات ----------
# نحمّل داتاسيت tips (إذا ما اشتغل الإنترنت نقرأه من ملف tips.csv بنفس المجلد)
try:
    tips = sns.load_dataset("tips")
except Exception:
    tips = pd.read_csv("tips.csv")

# العمود يلي أنشأناه بمهمة 9: نسبة الإكرامية من الفاتورة
tips["tip_percentage"] = tips["tip"] / tips["total_bill"] * 100


# دالة بسيطة تعطينا القرار حسب قيمة p
def القرار(قيمة_p):
    if قيمة_p < مستوى_الدلالة:
        return "دال إحصائيًا"
    else:
        return "غير دال إحصائيًا"


# =====================================================
# الجزء 1 — مفهوم اختبار الفرضيات (إجابات بكلماتي)
# =====================================================
print("=" * 60)
print("الجزء 1 — مفهوم اختبار الفرضيات")
print("=" * 60)

# H0 (الفرضية الصفرية): ما في فرق حقيقي، وأي فرق بالعينة هو صدفة.
# H1 (الفرضية البديلة): في فرق حقيقي فعلاً.
# p-value: احتمال نشوف فرق بحجم يلي شفناه (أو أكبر) بالصدفة لو H0 صحيحة.

سؤال_1 = """
س1: ليش الفرق بين 5 مدخنين و5 غير مدخنين مش كافي؟
ج: لأن العينة صغيرة جدًا، ولو غيّرنا الزبائن الخمسة ممكن يتغير الفرق أو
ينعكس. الفرق ممكن يكون صدفة بسبب اختيار هالأشخاص بالذات، فما بنقدر
نقول بثقة إن المدخنين بيكرّمون أكتر.
"""

سؤال_2 = """
س2: شو معنى p-value = 0.03؟
ج: معناه إنو لو ما في فرق حقيقي، احتمال نشوف فرق بهالحجم بالصدفة هو 3%
فقط. هاد دليل قوي ضد H0 فبنرفضها (لأنه أقل من 0.05)، بس هو ما "يثبت"
H1 بنسبة 100%، لأنه ضل في احتمال صغير (3%) يكون الفرق صدفة.
"""

سؤال_3 = """
س3: ليش 0.05 رقم متعارف عليه مش قانون رياضي؟
ج: لأنه مجرد اتفاق بين الباحثين. كل مجال بيختار حسب حساسية القرار؛
مثلاً بالأدوية والطب بيستخدموا 0.01 أو أقل لأن الخطأ خطير، وبالتسويق
ممكن يكفي 0.05 أو حتى 0.10 لأن الخطأ أقل تكلفة.
"""

print(سؤال_1)
print(سؤال_2)
print(سؤال_3)


# =====================================================
# الجزء 2 — T-test: مقارنة متوسطين
# =====================================================
print("=" * 60)
print("الجزء 2 — T-test")
print("=" * 60)

# ---------- السؤال الأول: المدخنين مقابل غير المدخنين (tip_percentage) ----------
المدخنين = tips[tips["smoker"] == "Yes"]["tip_percentage"]
غير_المدخنين = tips[tips["smoker"] == "No"]["tip_percentage"]

print("\n--- هل المدخنين بيكرّمون أكتر؟ ---")
print(f"متوسط نسبة الإكرامية للمدخنين: {المدخنين.mean():.2f}%")
print(f"متوسط نسبة الإكرامية لغير المدخنين: {غير_المدخنين.mean():.2f}%")
print(f"الفرق بالعين المجردة: {المدخنين.mean() - غير_المدخنين.mean():.2f}%")

t_المدخنين, p_المدخنين = stats.ttest_ind(المدخنين, غير_المدخنين)
print(f"p-value: {p_المدخنين}")
قرار_المدخنين = القرار(p_المدخنين)
print(f"القرار: {قرار_المدخنين}")
if p_المدخنين < مستوى_الدلالة:
    print("الفرق مش صدفة على الأغلب.")
else:
    print("ما في دليل كافي، الفرق ممكن يكون صدفة.")

# ---------- السؤال الثاني: الغدا مقابل العشا (total_bill) ----------
فاتورة_الغدا = tips[tips["time"] == "Lunch"]["total_bill"]
فاتورة_العشا = tips[tips["time"] == "Dinner"]["total_bill"]

print("\n--- هل متوسط الفاتورة مختلف بين الغدا والعشا؟ ---")
print(f"متوسط فاتورة الغدا: {فاتورة_الغدا.mean():.2f}")
print(f"متوسط فاتورة العشا: {فاتورة_العشا.mean():.2f}")
print(f"الفرق بالعين المجردة: {فاتورة_العشا.mean() - فاتورة_الغدا.mean():.2f}")

t_الوقت, p_الوقت = stats.ttest_ind(فاتورة_الغدا, فاتورة_العشا)
print(f"p-value: {p_الوقت}")
قرار_الوقت = القرار(p_الوقت)
print(f"القرار: {قرار_الوقت}")


# =====================================================
# الجزء 3 — Chi-Square Test
# =====================================================
print("\n" + "=" * 60)
print("الجزء 3 — Chi-Square Test")
print("=" * 60)

# ---------- السؤال الأول: اليوم والتدخين ----------
جدول_اليوم_التدخين = pd.crosstab(tips["day"], tips["smoker"])
print("\n--- هل اليوم مرتبط بكون الزبون مدخن؟ ---")
print("جدول التقاطع:")
print(جدول_اليوم_التدخين)

chi2_اليوم, p_اليوم, درجات_الحرية_1, المتوقع_1 = chi2_contingency(جدول_اليوم_التدخين)
print(f"p-value: {p_اليوم}")
قرار_اليوم = القرار(p_اليوم)
print(f"القرار: {قرار_اليوم}")
if p_اليوم < مستوى_الدلالة:
    print("في علاقة حقيقية بين اليوم وكون الزبون مدخن.")
else:
    print("الاثنين مستقلين عن بعض إحصائيًا.")

# ---------- السؤال الثاني: الجنس والوقت ----------
جدول_الجنس_الوقت = pd.crosstab(tips["sex"], tips["time"])
print("\n--- هل في علاقة بين الجنس والوقت (غدا/عشا)؟ ---")
print("جدول التقاطع:")
print(جدول_الجنس_الوقت)

chi2_الجنس, p_الجنس, درجات_الحرية_2, المتوقع_2 = chi2_contingency(جدول_الجنس_الوقت)
print(f"p-value: {p_الجنس}")
قرار_الجنس = القرار(p_الجنس)
print(f"القرار: {قرار_الجنس}")
if p_الجنس < مستوى_الدلالة:
    print("في علاقة حقيقية بين الجنس ووقت الزيارة.")
else:
    print("الاثنين مستقلين عن بعض إحصائيًا.")


# =====================================================
# الجزء 4 — التقرير النهائي
# =====================================================
print("\n" + "=" * 60)
print("الجزء 4 — التقرير النهائي")
print("=" * 60)

جدول_التقرير = pd.DataFrame({
    "السؤال": [
        "هل المدخنين بيكرّمون أكتر؟",
        "هل الغدا والعشا مختلفين بالفاتورة؟",
        "هل اليوم مرتبط بكون الزبون مدخن؟",
        "هل الجنس مرتبط بالوقت (غدا/عشا)؟",
    ],
    "الاختبار المستخدم": ["T-test", "T-test", "Chi-Square", "Chi-Square"],
    "p-value": [
        round(p_المدخنين, 4),
        round(p_الوقت, 4),
        round(p_اليوم, 4),
        round(p_الجنس, 4),
    ],
    "دال إحصائيًا؟": [
        "نعم" if p_المدخنين < مستوى_الدلالة else "لا",
        "نعم" if p_الوقت < مستوى_الدلالة else "لا",
        "نعم" if p_اليوم < مستوى_الدلالة else "لا",
        "نعم" if p_الجنس < مستوى_الدلالة else "لا",
    ],
})
print(جدول_التقرير.to_string(index=False))

# ---------- الفقرة الختامية لمدير المطعم (بدون مصطلحات إحصائية) ----------
# نبني الفقرة من النتائج الفعلية عشان تكون دايمًا مطابقة للأرقام
جمل_حقيقية = []
جمل_صدفة = []

if p_المدخنين < مستوى_الدلالة:
    جمل_حقيقية.append("الزبائن المدخنين بيتركوا إكرامية مختلفة عن غير المدخنين")
else:
    جمل_صدفة.append("الفرق البسيط بين إكرامية المدخنين وغير المدخنين")

if p_الوقت < مستوى_الدلالة:
    جمل_حقيقية.append("حجم الفاتورة وقت العشا يختلف فعلاً عن وقت الغدا")
else:
    جمل_صدفة.append("الفرق بين فاتورة الغدا والعشا")

if p_اليوم < مستوى_الدلالة:
    جمل_حقيقية.append("عدد المدخنين بيختلف حسب اليوم من الأسبوع")
else:
    جمل_صدفة.append("اختلاف عدد المدخنين من يوم ليوم")

if p_الجنس < مستوى_الدلالة:
    جمل_حقيقية.append("نسبة الرجال والنساء بتختلف بين الغدا والعشا")
else:
    جمل_صدفة.append("اختلاف نسبة الرجال والنساء بين الغدا والعشا")

الفقرة = "الخلاصة لمدير المطعم: "
if جمل_حقيقية:
    الفقرة += "الفروقات التالية حقيقية ومتكررة وتستحق الاعتماد عليها بالقرارات: "
    الفقرة += "، ".join(جمل_حقيقية) + ". "
else:
    الفقرة += "ما لقينا أي فرق حقيقي مؤكد بين المجموعات يلي فحصناها. "
if جمل_صدفة:
    الفقرة += "أما هالفروقات فشكلها صدفة على الأغلب، وما في داعي تاخد قرار بناءً عليها: "
    الفقرة += "، ".join(جمل_صدفة) + ". "
الفقرة += "ننصح بمراجعة النتائج مرة ثانية مع بيانات أكتر قبل أي تغيير كبير."

print()
print(الفقرة)
